// The Gmail payment script's parser (app/payments/LOCKqz-payments.gs): real alerts accepted, forged
// or outgoing ones refused. Runs the real .gs file in a sandbox with fake Gmail messages.
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
const GS = process.env.LQZ_GS || join(dirname(fileURLToPath(import.meta.url)), "..", "payments", "LOCKqz-payments.gs");
const src = readFileSync(GS, "utf8");
const ctx = {}; vm.createContext(ctx); vm.runInContext(src + "\nthis.parse = parse;", ctx);
let pass = 0, fail = 0; const check = (m, c, i = "") => { if (c) { pass++; console.log("  ok:", m); } else { fail++; console.log("  FAIL:", m, i); } };
const OWN = "lockqz.pay@gmail.com", OPTS = { owners: [OWN] };
// A raw alert: Gmail's DKIM verdict, the sender's DKIM-Signature (h= lists the signed headers), To:.
const msg = (auth, subject, body, { id = "m1", to = OWN, d = null, h = "from:to:subject:date" } = {}) => {
  const dom = d || ((auth.match(/header\.(?:i=[^@\s;]*@|d=)([A-Za-z0-9.-]+)/) || [])[1] || "x.com");
  return { getRawContent: () => `Authentication-Results: mx.google.com;\r\n       ${auth}\r\nDKIM-Signature: v=1; a=rsa-sha256; d=${dom}; s=x;\r\n\th=${h}; bh=abc; b=def\r\nFrom: x\r\nTo: ${to}\r\nDelivered-To: ${OWN}\r\nSubject: ${subject}\r\n\r\n${body}`,
           getSubject: () => subject, getPlainBody: () => body, getId: () => id };
};
const parse = (m, o = OPTS) => ctx.parse(m, o);
const VENMO_OK = "dkim=pass header.i=@venmo.com header.s=x header.b=y; spf=pass";
let p = parse(msg(VENMO_OK, "Al Student paid you $5.00", "Al Student paid you $5.00\nLQS4M8TX\nTransaction ID 123456"));
check("real Venmo alert parsed; txn = Venmo's own transaction id", p && p.amount === 5 && p.note === "LQS4M8TX" && p.via === "venmo" && p.payer === "Al Student" && p.txn === "venmo:123456" && p.msg === "m1" && !p.needs_review, JSON.stringify(p));
p = parse(msg(VENMO_OK, "Al Student paid you $5.00", "Al Student paid you $5.00\nLQS4M8TX\nTransaction ID 123456", { id: "m2" }));
check("same payment re-sent under another Gmail id -> same txn (deduped by LOCKqz)", p && p.txn === "venmo:123456");
p = parse(msg("dkim=fail header.i=@venmo.com", "Al paid you $5.00", "LQS4M8TX"));
check("failed DKIM refused", p === null);
p = parse(msg("dkim=pass header.i=@evil-venmo.com", "Al paid you $5.00", "LQS4M8TX"));
check("look-alike domain refused", p === null);
p = parse(msg("dkim=pass header.i=@gmail.com", "Al paid you $5.00", "LQS4M8TX"));
check("forwarded/forged from gmail refused", p === null);
p = parse(msg(VENMO_OK, "You paid Bob $5.00", "LQS4M8TX"));
check("outgoing payment ignored", p === null);
p = parse(msg(VENMO_OK, "Bob requests $5.00", "LQS4M8TX"));
check("payment request ignored", p === null);
p = parse(msg(VENMO_OK, "Your transfer of $40.00 to your bank is complete", "Standard transfer $40.00"));
check("bank transfer notice ignored (H9)", p === null);
p = parse(msg("dkim=pass header.d=chase.com header.s=x", "You received money with Zelle", "Duke Bristow sent you $2,500.00\nMemo: LQ7K3PX\nConfirmation: ABC12345"));
check("Chase Zelle alert parsed (comma amount, confirmation id)", p && p.amount === 2500 && p.via === "zelle" && p.note === "LQ7K3PX" && p.txn === "zelle:ABC12345", JSON.stringify(p));
p = parse(msg("dkim=pass header.i=@alerts.bankofamerica.com", "Zelle payment received", "You received $5.00 from Cy. Memo: for cy@usc.edu"));
check("BofA subdomain + email memo", p && p.amount === 5 && /cy@usc.edu/.test(p.note), JSON.stringify(p));
p = parse(msg("dkim=pass header.i=@alerts.bankofamerica.com", "Zelle payment received", "You received $1.00 from Cy.\nMemo: LQS4M8TX $180.00"));
check("memo saying $180 on a $1 payment counts as $1", p && p.amount === 1, JSON.stringify(p));
p = parse(msg("dkim=pass header.i=@alerts.bankofamerica.com", "Zelle payment received", "Memo: LQS4M8TX paid $180\nAmount: $1.00"));
check("memo before the amount: still the real $1", p && p.amount === 1, JSON.stringify(p));
p = parse(msg("dkim=pass header.i=@alerts.bankofamerica.com", "You received a deposit", "ACH deposit $180.00 from JOHN DOE\nLQS4M8TX"));
check("bank transfer with memo -> counted automatically (via bank)", p && !p.needs_review && p.via === "bank" && p.note === "LQS4M8TX" && p.amount === 180, JSON.stringify(p));
p = parse(msg("dkim=pass header.i=@alerts.bankofamerica.com", "You received a deposit", "Payroll deposit $2,000.00"));
check("other deposits ignored", p === null, JSON.stringify(p));
console.log("H9 parsing: codes typed with spaces/dashes/lowercase, amounts without cents");
p = parse(msg(VENMO_OK, "Bo paid you $5", "Bo paid you $5\nlqs-4m8tx thanks"));
check("'$5' (no cents) + 'lqs-4m8tx' -> 5, LQS4M8TX", p && p.amount === 5 && p.note === "LQS4M8TX", JSON.stringify(p));
p = parse(msg(VENMO_OK, "Bo paid you $5", "Bo paid you\nLQ S 4M8TX"));
check("'LQ S 4M8TX' -> LQS4M8TX", p && p.note === "LQS4M8TX", JSON.stringify(p));
p = parse(msg(VENMO_OK, "Bo paid you", "Bo paid you\nLQS4M8TX"));
check("signed alert with no readable amount -> posted for review, not dropped", p && p.needs_review === true && /amount/.test(p.review_reason), JSON.stringify(p));
console.log("H3 replays / forgeries");
p = parse(msg(VENMO_OK, "Al paid you $5.00", "LQS4M8TX", { to: "attacker@gmail.com" }));
check("someone else's real alert re-sent here (signed To: is not us) -> review only", p && p.needs_review === true && /To:/.test(p.review_reason), JSON.stringify(p));
p = parse(msg(VENMO_OK, "Al paid you $5.00", "LQS4M8TX", { h: "from:subject:date" }));
check("To: not covered by the DKIM signature -> review only", p && p.needs_review === true, JSON.stringify(p));
p = parse(msg("dkim=pass header.d=zellepay.com", "You received $5.00 with Zelle", "Memo: LQS4M8TX"));
check("zellepay.com alert -> review only (not a confirmed receiving alert)", p && p.needs_review === true && /zellepay/.test(p.review_reason), JSON.stringify(p));
p = parse(msg("dkim=pass header.d=zellepay.com", "You received $5.00 with Zelle", "Memo: LQS4M8TX"), { owners: [OWN], zellepayOk: true });
check("zellepay.com with ZELLEPAY_OK=1 -> counts", p && !p.needs_review && p.amount === 5, JSON.stringify(p));
p = parse(msg(VENMO_OK, "Al paid you $5.00", "LQS4M8TX"), {});
check("owner address unknown -> review only", p && p.needs_review === true, JSON.stringify(p));
console.log(`\nRESULT: ${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
